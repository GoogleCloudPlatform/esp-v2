// TestExactOpenAutoCORS verifies Service Control reporting for both an open
// exact GET request and its autogenerated CORS OPTIONS preflight request.
func TestExactOpenAutoCORS(t *testing.T) {
	s := env.NewTestEnv(platform.TestAPIGWServiceControlCore, platform.EchoSidecar)
	defer s.TearDown(t)
	s.SetAllowCors()
	s.OverrideUsage(&confpb.Usage{
		Rules: []*confpb.UsageRule{
			{
				Selector:               "1.echo_api_endpoints_cloudesf_testing_cloud_goog.Simplegetcors",
				AllowUnregisteredCalls: true,
			},
		},
	})
	if err := s.Setup(utils.CommonArgs()); err != nil {
		t.Fatalf("s.Setup() failed: %v", err)
	}

	targetURL := s.ListenerURL("/simplegetcors")
	respHeaders, resp, err := utils.DoWithHeaders(targetURL, http.MethodGet, "", map[string]string{"Origin": "http://cloud.google.com"})
	if err != nil {
		t.Fatalf("utils.DoWithHeaders(%q, %q) failed: %v", targetURL, http.MethodGet, err)
	}
	if got, want := string(resp), "simple get message"; !strings.Contains(got, want) {
		t.Errorf("utils.DoWithHeaders(%q, %q) body = %q, want to contain %q", targetURL, http.MethodGet, got, want)
	}
	if got, want := respHeaders.Get("Access-Control-Allow-Origin"), "*"; got != want {
		t.Errorf("utils.DoWithHeaders(%q, %q) Access-Control-Allow-Origin = %q, want %q", targetURL, http.MethodGet, got, want)
	}

	scRequests, err := s.ServiceControlServer.GetRequests(1)
	if err != nil {
		t.Fatalf("s.ServiceControlServer.GetRequests(1) for GET %q failed: %v", targetURL, err)
	}
	wantGetSC := utils.ServiceControlExpectation{
		OperationName: "1.echo_api_endpoints_cloudesf_testing_cloud_goog.Simplegetcors",
		HTTPMethod:    http.MethodGet,
		HTTPStatus:    http.StatusOK,
	}
	if err := utils.VerifyReportRequest(scRequests[0], wantGetSC); err != nil {
		t.Errorf("utils.VerifyReportRequest(GET %q) failed: %v", targetURL, err)
	}

	corsHeaders, status, _, err := utils.DoCORSPreflight(t.Context(), targetURL, "http://cloud.google.com", http.MethodGet, "Authorization")
	if err != nil {
		t.Fatalf("utils.DoCORSPreflight(%q, %q) failed: %v", targetURL, http.MethodGet, err)
	}
	if status != http.StatusOK && status != http.StatusNoContent {
		t.Errorf("utils.DoCORSPreflight(%q, %q) status = %d, want 200 or 204", targetURL, http.MethodGet, status)
	}
	if got, want := corsHeaders.Get("Access-Control-Allow-Origin"), "*"; got != want {
		t.Errorf("utils.DoCORSPreflight(%q, %q) Access-Control-Allow-Origin = %q, want %q", targetURL, http.MethodGet, got, want)
	}

	scRequests, err = s.ServiceControlServer.GetRequests(1)
	if err != nil {
		t.Fatalf("s.ServiceControlServer.GetRequests(1) for OPTIONS %q failed: %v", targetURL, err)
	}
	wantOptionsSC := utils.ServiceControlExpectation{
		OperationName: "1.echo_api_endpoints_cloudesf_testing_cloud_goog.ESPv2_Autogenerated_CORS_Simplegetcors",
		HTTPMethod:    http.MethodOptions,
		HTTPStatus:    status,
	}
	if err := utils.VerifyReportRequest(scRequests[0], wantOptionsSC); err != nil {
		t.Errorf("utils.VerifyReportRequest(OPTIONS %q) failed: %v", targetURL, err)
	}
}

